// `text` is always the literal English string straight out of a CONFIGS
// field tuple / `config.title` — looked up as-is, falling back to the
// English original for anything not in the table (never renders blank).
export function useConfigLabel() {
  const { i18n } = useTranslation();
  const isPortuguese = i18n.language?.toLowerCase().startsWith("pt");
  return (text) => (isPortuguese ? (PT[text] ?? text) : text);
}
