// Arabic counts have more forms than English (zero, two, few, many); each
// takes the `_other` wording unless written out.
const withArabicPlurals = (ns) => {
  const out = { ...ns };
  for (const key of Object.keys(ns)) {
    if (!key.endsWith("_other")) continue;
    const base = key.slice(0, -"_other".length);
    for (const form of ["zero", "two", "few", "many"]) out[`${base}_${form}`] ??= ns[key];
  }
  return out;
};

export default Object.fromEntries(
  Object.entries({
    common,
    sidebar,
    layout,
    statusLabels,
    aml,
    cases,
  }).map(([name, ns]) => [name, withArabicPlurals(ns)]),
);
